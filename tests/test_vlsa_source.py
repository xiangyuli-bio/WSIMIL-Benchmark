def test_original_old_stack_token_ids_preserved_for_all_author_queries_and_edges():
    root,_=fixed();queries=json.loads((root/'tools/survival_text_prototypes.json').read_text())
    texts=['X.','a histopathology image suggesting','a very poor prognosis','a poor prognosis',
           'a good prognosis','a very good prognosis']
    for values in queries.values():
        if isinstance(values,list):texts+=values
    texts=list(dict.fromkeys(texts))
    module=tokenizer_module();tokenizer=module.get_tokenizer()
    tokens=module.tokenize(tokenizer,texts)
    assert len(texts)==51 and tokens.shape==(51,128) and (tokens[:,-1]==0).all()
    # Hashes were independently generated by the unmodified source tokenizer
    # under author transformers4.41.2/tokenizers0.19.1, not by this adapter.
    assert hashlib.sha256(tokens[:,:127].contiguous().numpy().tobytes()).hexdigest()=='5f09be68abe4d28c46439c76f8225ec6566a1746fcb5bd759f74fbbcfd647514'
    edge=['\n H&E: tumour αβ + 10%.','  paired leading spaces in pathology','','a '+'morphology '*200]
    tokens=module.tokenize(tokenizer,edge)
    assert hashlib.sha256(tokens[:,:127].contiguous().numpy().tobytes()).hexdigest()=='94753eee3b5e79441e456d157b4227ed2ba4f596e0f5d194cc4c0eb7334df10d'
    assert module.tokenize(tokenizer,['X.'])[0,1].item()==1410


@pytest.mark.parametrize('events',[[1,1,0,1],[1,0,1,0],[0,0,1,1]])
def test_literal_ifmle_and_squared_emd_equal_independent_formula_and_gradient(events):
    logits=torch.tensor([[1.,2.,3.],[.4,-.2,.3],[-1.,2.,0.],[.8,.9,-.1]],dtype=torch.float64,requires_grad=True)
    t=torch.tensor([0,1,2,0]);e=torch.tensor(events);scale=torch.tensor(7.,requires_grad=True)
    loss,parts=objective(logits,t,e,scale)
    p=logits.softmax(-1)
    mle=-(e*p[torch.arange(4),t].clamp_min(1e-7).log()
          +(1-e)*(1-p.cumsum(-1)[torch.arange(4),t]).clamp_min(1e-7).log()).mean()
    target=torch.zeros_like(p)
    for i,(index,event) in enumerate(zip(t,e)):
        target[i,index]=1
        if not event:target[i,index+1:]=1
    distribution=((1-e[:,None])*((1-target)*p+target*scale.detach())+e[:,None]*p).softmax(-1)
    target_distribution=((2*target-1)*scale.detach()).softmax(-1)
    emd=(distribution.cumsum(-1)-target_distribution.cumsum(-1)).square().sum(-1).mean()
    torch.testing.assert_close(parts['ifmle'],mle)
    torch.testing.assert_close(parts['emd'],emd)
    ga,=torch.autograd.grad(loss,logits,retain_graph=True)
    gb,=torch.autograd.grad(mle+emd,logits)
    torch.testing.assert_close(ga,gb)
    assert torch.autograd.grad(loss,scale,allow_unused=True)[0] is None


