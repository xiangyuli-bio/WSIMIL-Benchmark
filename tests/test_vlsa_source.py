def test_original_float32_survival_curve_and_mean_are_distinct_from_hazard_product():
    incidence=torch.tensor([[.2,.3,.1,.4]],dtype=torch.float32)
    means,survival=mean_times(incidence,[0.,1.,2.,3.])
    np.testing.assert_array_equal(survival,(1-incidence.cumsum(-1)).clamp_min(0).numpy().astype(np.float64))
    np.testing.assert_allclose(means,[1.3],atol=1e-6)
    assert not np.allclose(survival,(1-incidence).cumprod(-1))
    assert source_concordance([1.,2.,3.],[1,1,1],[1.,2.,3.])==1.
    assert source_concordance([1.,2.,3.],[1,1,1],[3.,2.,1.])==0.


