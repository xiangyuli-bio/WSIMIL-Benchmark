def test_training_event_intervals_auto_rank_and_right_open_boundaries():
    # Nine events -> original ceil(sqrt9)=3. Censored large follow-up must not
    # influence interior event edges, nor is any held-out max consulted.
    t=np.r_[np.arange(1,10),1000.];e=np.r_[np.ones(9),0]
    bins=time_bins(t,e)
    np.testing.assert_array_equal(bins,[0,3,6,np.inf])
    np.testing.assert_array_equal(np.searchsorted(bins,[.1,3,6,100000],side='right')-1,[0,1,2,2])
    t[-1]=999999.;np.testing.assert_array_equal(time_bins(t,e),bins)


