def test_actual_full_pretrained_text_and_six_learned_parameter_groups():
    torch.set_num_threads(2);root,_=fixed()
    m=build_network(WEIGHTS,root/'tools/survival_prompts.json',root/'tools/survival_text_prototypes.json','tcga_brca_0',4)
    expected={'logit_scale':(),'prompt_learner.context_embeds':(4,768),
        'prompt_learner.rank_embeds':(4,4,768),'mil_encoder.visual_adapter.weight':(512,512),
        'mil_encoder.visual_adapter.bias':(512,),'mil_encoder.Q.residual_features':(10,512)}
    assert {n:tuple(p.shape) for n,p in m.named_parameters() if p.requires_grad}==expected
    assert len(m.prompt_encoder.transformer.resblocks)==12
    assert m.prompt_encoder.transformer.resblocks[0].attn.num_heads==12
    assert m.prompt_encoder.token_embedding.weight.shape==(32007,768)
    assert m.prompt_encoder.positional_embedding.shape==(128,768)
    assert m.prompt_encoder.attn_mask.shape==(128,128)
    assert m.prompt_encoder.attn_mask[0,1].isneginf()
    assert all(not p.requires_grad for p in m.prompt_encoder.parameters())
    x=torch.randn(1,19,512);logits,visual,text=m(x)
    expected_logits=m.get_logit_scale()*torch.nn.functional.normalize(m.mil_encoder(x),dim=-1)@torch.nn.functional.normalize(m.forward_text_only(),dim=-1).T
    torch.testing.assert_close(logits,expected_logits)
    loss,_=objective(logits,torch.tensor([1]),torch.tensor([1]),m.get_logit_scale());loss.backward()
    for n,p in m.named_parameters():
        if p.requires_grad:
            assert p.grad is not None and torch.isfinite(p.grad).all() and p.grad.abs().sum()>0,n
        else:assert p.grad is None,n
    m.eval()
    with torch.no_grad():assert m(torch.randn(1,1,512))[0].shape==(1,4)


